    "   - 只建骨架 (manifest + app.json + 空 files/), status=draft\n"
    "   - 不传 files 字段 (向后兼容才保留, 别用)\n"
    f"2) weave_app_write_file(app_name, rel_path, content)  ← auto-pass, 多次\n"
    "   - 写源码: handler.py / utils.py / templates/x.html / scripts/foo.py 等\n"
    "   - rel_path 相对 files/ 根, 不能 ../, 不能覆盖 manifest/app.json/meta/runs/logs\n"
