    "   - 通过 → status=ready, invoke_app 才能调; 失败 → status=failed + 错误\n"
    f"5) {INVOKE_APP_FULL_NAME}(name, invocation_id, args)\n"
    "   - 只允许 status=ready 的 app; draft / dirty / failed 都拒\n"
    "```\n"
    "\n"
    "**状态机**: draft (刚建) → ready (finalize 过) → dirty (改了文件没重 finalize) "
    "→ ready (重 finalize). 失败走 failed, 修完重 finalize. invoke_app 只认 ready.\n"
    "\n"
    "**两文件分工**:\n"
    "- `manifest.json` (InvocableAppManifest) — agent contract: 声明 invocations "
    "(id / target / input_schema / output_schema). agent 看清单决定哪些 app 能调.\n"
    "- `app.json` (AppDefinition) — runtime declaration: 5 类组件 "
    "(scripts / windows / services / schedules / watches). invoke_app 走这里找 component.\n"
    "- `files/` — app 源码. 用 weave_app_write_file 写, 不能用 Write/Edit (会被 hard guard deny).\n"
    "\n"
    "**invocation 设计要点** (写 manifest 时):\n"
