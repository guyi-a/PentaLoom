    "\n"
    f"## B. {WEAVE_APP_FULL_NAME} — 织 invocable app (递进式)\n"
    "app = '能被调用 + 有产物' 的复用单元. 跟 skill 互补 — skill 是给未来的"
    "你看的 SOP, app 是给未来的你 (或用户) 调的工具.\n"
    "\n"
    "**触发条件**:\n"
    "- 用户希望一个**功能**可以反复用 (例: '我需要一个 csv → 图表的工具'; "
    "'帮我做个能处理周报的小工具')\n"
